for line in text:
    m = pat.match(line)
    if m:
        lab = m.group(2)
        if lab in MAP:
            line = m.group(1) + '"' + MAP[lab] + '"' + line[m.end(2)+1:]
            cnt += 1
        else:
            miss.append(lab)
    out.append(line)
